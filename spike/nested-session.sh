#!/usr/bin/env bash
# A nested Hyprland to test 42Hz in.
#
# Verifying responsive behaviour means putting the window at a series of exact
# geometries and looking at each one. That cannot be done on a desktop someone
# is using: the parent tiling layout undoes every resize within a second,
# focus-follows-mouse hands keystrokes to whatever is under the pointer, and a
# screenshot catches whatever happened to be on top. A nested compositor on its
# own Wayland socket has none of those problems -- one window, no layout policy
# but ours, deterministic focus, and `grim` capturing exactly the output we
# sized.
#
# Everything here is disposable and lives in $XDG_RUNTIME_DIR. It reads no user
# configuration and writes none: the nested session gets a generated config
# passed with -c, so ~/.config/hypr is neither read nor touched.
#
#   ./spike/nested-session.sh start [WxH]   start it (default 1920x1080)
#   ./spike/nested-session.sh status        pid, socket, output and client sizes
#   ./spike/nested-session.sh size WxH      resize the nested output
#   ./spike/nested-session.sh window WxH    float and size the 42Hz window exactly
#   ./spike/nested-session.sh state tiled|floating|fullscreen
#   ./spike/nested-session.sh run CMD...    run a command against it
#   ./spike/nested-session.sh ctl ARGS...   hyprctl against it
#   ./spike/nested-session.sh key KEY...    send keys, refusing unless 42Hz has focus
#   ./spike/nested-session.sh shot FILE     screenshot the 42Hz window
#   ./spike/nested-session.sh raise         bring the nested session to the front
#   ./spike/nested-session.sh stop          kill it
#
# A headless session would be tidier -- no window on the user's screen at all --
# but this Hyprland's aquamarine has no backend-selection switch and no
# --headless flag, so the nested window is the only route.

set -euo pipefail

STATE="${XDG_RUNTIME_DIR:-/tmp}/42hz-nested"
CONFIG="$STATE/hyprland.conf"
PIDFILE="$STATE/pid"
SIGFILE="$STATE/signature"
SOCKFILE="$STATE/socket"

# The class Hyprland matches on, and the only window the harness will type at.
APP_ID=io.github.chizzler.42Hz

die() { echo "nested-session: $*" >&2; exit 1; }

write_config() {
    local geom="$1"
    mkdir -p "$STATE"
    cat > "$CONFIG" <<EOF
# Generated by spike/nested-session.sh. Disposable.
#
# Everything that would make a screenshot ambiguous is off: no gaps, no border,
# no rounding, no blur, no shadow, no animation. A window that is alone on the
# output therefore measures exactly the output size, which is what makes
# "resize the monitor" a usable way to set a window geometry.
monitor = , ${geom}@60, 0x0, 1

general {
    gaps_in = 0
    gaps_out = 0
    border_size = 0
    allow_tearing = false
}

decoration {
    rounding = 0
    blur {
        enabled = false
    }
    shadow {
        enabled = false
    }
}

animations {
    enabled = false
}

misc {
    disable_hyprland_logo = true
    disable_splash_rendering = true
    disable_watchdog_warning = true
    force_default_wallpaper = 0
    background_color = 0xff000000
    disable_autoreload = true
}

# Force continuous rendering. With VFR on, a nested compositor showing static
# content stops producing frames, and grim then waits forever for a
# screencopy that never arrives -- so a capture of a silent, still window hangs
# while the identical capture of a live spectrum returns at once. That is a
# property of the harness, not of 42Hz, and it made an idle window look like a
# wedged one.
#
# The option moved: it is debug:vfr in this Hyprland, and misc:vfr -- where
# it used to live -- is now an unknown key, which raises a config-error banner
# that is drawn into the output and reserves space in it.
debug {
    vfr = false
}

# The nested pointer is drawn into the nested output, so grim captures it and
# every screenshot carries an arrow somewhere over the spectrum. Hiding it when
# idle is enough: the harness drives this session with dispatchers and wtype,
# and never moves the pointer.
cursor {
    inactive_timeout = 1
    no_warps = true
}

# Focus follows the dispatcher, never the pointer. The pointer is the parent
# session's, and it is why keystrokes went into other people's windows before.
input {
    follow_mouse = 0
}

# Nothing is bound. The harness drives this session; a stray key must not be
# able to do anything to it.
EOF
}

instance_signature() {
    [[ -f "$SIGFILE" ]] && cat "$SIGFILE"
}

# Hyprland will not take --socket without --wayland-fd (that pair is for socket
# handover, not for naming), so the nested display name is whichever wayland-N
# it picked. Recorded at startup rather than guessed.
socket_name() {
    [[ -f "$SOCKFILE" ]] && cat "$SOCKFILE"
}

hctl() {
    local sig
    sig="$(instance_signature)" || die "not running"
    [[ -n "$sig" ]] || die "not running"
    hyprctl -i "$sig" "$@"
}

running() {
    [[ -f "$PIDFILE" ]] && kill -0 "$(cat "$PIDFILE")" 2>/dev/null
}

cmd_start() {
    local geom="${1:-1920x1080}"

    if running; then
        echo "already running (pid $(cat "$PIDFILE"), WAYLAND_DISPLAY=$(socket_name))"
        return 0
    fi

    [[ -n "${WAYLAND_DISPLAY:-}" ]] || die "no parent WAYLAND_DISPLAY; nothing to nest inside"

    rm -rf "$STATE"
    write_config "$geom"

    local before
    before="$(ls "${XDG_RUNTIME_DIR}" | grep -E '^wayland-[0-9]+$' | sort)"

    # The parent's instance signature must not leak in, or hyprctl inside the
    # nested session would talk to the desktop we are trying to stay out of.
    env -u HYPRLAND_INSTANCE_SIGNATURE \
        HYPRLAND_NO_CRASHREPORTER=1 \
        Hyprland -c "$CONFIG" \
        > "$STATE/hyprland.log" 2>&1 &
    echo $! > "$PIDFILE"

    local pid
    pid="$(cat "$PIDFILE")"

    # Wait for a new socket to appear, then for the instance to answer hyprctl.
    # Both, in that order: the socket exists before the compositor is ready to
    # be driven.
    local i socket=""
    for ((i = 0; i < 100; i++)); do
        socket="$(comm -13 <(echo "$before") \
                           <(ls "${XDG_RUNTIME_DIR}" | grep -E '^wayland-[0-9]+$' | sort) | head -1)"
        [[ -n "$socket" ]] && break
        kill -0 "$pid" 2>/dev/null || die "died on startup; see $STATE/hyprland.log"
        sleep 0.1
    done
    [[ -n "$socket" ]] || die "no new socket after 10s; see $STATE/hyprland.log"
    echo "$socket" > "$SOCKFILE"

    local sig=""
    for ((i = 0; i < 100; i++)); do
        sig="$(hyprctl instances -j 2>/dev/null | jq -r --argjson p "$pid" '.[] | select(.pid == $p) | .instance' || true)"
        [[ -n "$sig" && "$sig" != "null" ]] && break
        sleep 0.1
    done
    [[ -n "$sig" && "$sig" != "null" ]] || die "instance never registered; see $STATE/hyprland.log"
    echo "$sig" > "$SIGFILE"

    # Hyprland greets a new instance with timed warning banners -- a .conf
    # deprecation notice, and one about not being started by start-hyprland --
    # and draws them into its own output, where grim captures them across the
    # top of whatever is being photographed. They expire on their own in about
    # fifteen seconds. Waiting here once is better than every caller learning
    # to distrust its first few captures.
    sleep 16

    echo "started: pid $pid, WAYLAND_DISPLAY=$socket, instance $sig, output $geom"
}

cmd_stop() {
    running || { echo "not running"; rm -rf "$STATE"; return 0; }
    local pid
    pid="$(cat "$PIDFILE")"
    kill "$pid" 2>/dev/null || true
    local i
    for ((i = 0; i < 50; i++)); do
        kill -0 "$pid" 2>/dev/null || break
        sleep 0.1
    done
    kill -9 "$pid" 2>/dev/null || true
    rm -rf "$STATE"
    echo "stopped"
}

# Resizing the nested output is how a window gets an exact geometry: with no
# gaps and no border, the single tiled window is the output.
cmd_size() {
    local geom="${1:?usage: size WxH}"
    local name
    name="$(hctl monitors -j | jq -r '.[0].name')"
    hctl keyword monitor "${name},${geom}@60,0x0,1" >/dev/null
    echo "$name -> $geom"
}

# The nested output cannot be sized freely: it is a surface in the parent
# session, so the parent's layout decides how big it is and a monitor rule loses
# that argument. A floating window inside the nested session has no such
# problem -- `resizewindowpixel exact` lands on the pixel -- so the sweep sets
# window geometry, not output geometry, and the output is only a ceiling.
cmd_window() {
    local geom="${1:?usage: window WxH}"
    local w="${geom%x*}" h="${geom#*x}"

    hctl dispatch setfloating "class:$APP_ID" >/dev/null
    hctl dispatch resizewindowpixel "exact $w $h,class:$APP_ID" >/dev/null
    hctl dispatch centerwindow >/dev/null 2>&1 || true

    # Report what was actually granted rather than what was asked for: a
    # compositor is entitled to refuse, and a sweep that assumes otherwise
    # writes the wrong caption under the right picture.
    local i got
    for ((i = 0; i < 20; i++)); do
        got="$(hctl clients -j | jq -r --arg c "$APP_ID" '.[] | select(.class == $c) | "\(.size[0])x\(.size[1])"')"
        [[ "$got" == "$geom" ]] && break
        sleep 0.1
    done
    echo "$got"
}

cmd_state() {
    hctl dispatch focuswindow "class:$APP_ID" >/dev/null
    case "${1:?usage: state tiled|floating|fullscreen}" in
        tiled)
            hctl dispatch fullscreenstate 0 0 >/dev/null
            hctl dispatch settiled "class:$APP_ID" >/dev/null ;;
        floating)
            hctl dispatch fullscreenstate 0 0 >/dev/null
            hctl dispatch setfloating "class:$APP_ID" >/dev/null ;;
        fullscreen)
            hctl dispatch fullscreenstate 2 2 >/dev/null ;;
        *) die "unknown state: $1" ;;
    esac
    sleep 0.4
    hctl clients -j | jq -r --arg c "$APP_ID" \
        '.[] | select(.class == $c) | "\(.size[0])x\(.size[1]) floating=\(.floating) fullscreen=\(.fullscreen)"'
}

cmd_run() {
    local sig
    sig="$(instance_signature)" || die "not running"
    WAYLAND_DISPLAY="$(socket_name)" HYPRLAND_INSTANCE_SIGNATURE="$sig" "$@"
}

# Refuse to type unless 42Hz really has focus. Inside the nested session that
# should always be true, which is the point -- if it is ever false, something
# is wrong and a keystroke is the worst way to find out.
cmd_key() {
    hctl dispatch focuswindow "class:$APP_ID" >/dev/null
    local active
    active="$(hctl activewindow -j | jq -r '.class // ""')"
    [[ "$active" == "$APP_ID" ]] || die "refusing to send keys: focus is on '${active:-nothing}', not $APP_ID"
    cmd_run wtype "$@"
}

cmd_focus() {
    hctl dispatch focuswindow "class:$APP_ID" >/dev/null 2>&1 || true
}

# Captures the 42Hz window rather than the whole nested output, so the image is
# the geometry under test and nothing else.
#
# The timeout is not paranoia. A nested compositor renders only while its own
# window is getting frame callbacks from the parent, so anything that stops
# those stops screencopy dead and grim blocks forever: the window being covered,
# or -- the one that will catch you -- the user switching to another workspace,
# because an unmapped workspace gets no callbacks at all. Failing in ten seconds
# with the reason beats a sweep that hangs with nothing to show for it.
#
# There is no fix from inside the nested session. It has to be visible on the
# parent's current workspace while a sweep runs.
cmd_shot() {
    local out="${1:?usage: shot FILE}"
    local rect
    rect="$(hctl clients -j | jq -r --arg c "$APP_ID" \
        '.[] | select(.class == $c) | "\(.at[0]),\(.at[1]) \(.size[0])x\(.size[1])"')"
    [[ -n "$rect" ]] || die "no $APP_ID window to capture"

    if ! timeout 10 env WAYLAND_DISPLAY="$(socket_name)" grim -g "$rect" "$out"; then
        die "grim did not return: the nested session is not being drawn. It must be visible on the parent's ACTIVE workspace -- check the workspace first, then run 'nested-session.sh raise'."
    fi

    echo "$out"
}

# Bring the nested session to the front of the PARENT session, which is the one
# thing here that reaches outside the sandbox -- and is needed because a covered
# nested compositor stops rendering entirely.
#
# This has to go through `hyprctl eval` and Lua, while everything aimed at the
# nested session uses plain `hyprctl dispatch`. That is not inconsistency: a
# Hyprland configured in Lua (~/.config/hypr/hyprland.lua, no hyprland.conf)
# parses `hyprctl dispatch` as a Lua expression, so `dispatch focuswindow
# class:foo` comes back as a syntax error near `class`. The nested session is
# started with `-c` on a generated .conf, so it runs the classic parser and
# takes native dispatchers. Which form works is decided by how the instance
# was configured, not by the Hyprland version.
#
# `focus` takes the window OBJECT. Passing an address string returns ok and
# does nothing, which is worse than an error.
cmd_raise() {
    local pid
    pid="$(cat "$PIDFILE" 2>/dev/null)" || die "not running"

    hyprctl eval "local w
        for _, x in ipairs(hl.get_windows()) do
            if x.pid == $pid then w = x end
        end
        if w then hl.dispatch(hl.dsp.focus({ window = w })) end" >/dev/null
}

cmd_status() {
    if running; then
        echo "running: pid $(cat "$PIDFILE"), WAYLAND_DISPLAY=$(socket_name), instance $(instance_signature)"
        hctl monitors -j | jq -r '.[] | "output \(.name) \(.width)x\(.height)"'
        hctl clients -j | jq -r '.[] | "client \(.class) \(.size[0])x\(.size[1]) floating=\(.floating) fullscreen=\(.fullscreen)"'
    else
        echo "not running"
    fi
}

case "${1:-}" in
    start)  shift; cmd_start "$@" ;;
    stop)   shift; cmd_stop ;;
    status) shift; cmd_status ;;
    size)   shift; cmd_size "$@" ;;
    window) shift; cmd_window "$@" ;;
    state)  shift; cmd_state "$@" ;;
    run)    shift; cmd_run "$@" ;;
    ctl)    shift; hctl "$@" ;;
    key)    shift; cmd_key "$@" ;;
    focus)  shift; cmd_focus ;;
    shot)   shift; cmd_shot "$@" ;;
    raise)  shift; cmd_raise ;;
    *)      sed -n '2,30p' "$0" | sed 's/^# \?//' ; exit 1 ;;
esac
